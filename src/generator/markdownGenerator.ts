import { ExtractedFileContext, RelevanceResult } from '../models/relevance';
import { TaskContextStats } from '../models/task';
import { ProjectStructure } from '../scanner/projectStructure';
import { RelationshipGraph } from '../graph/relationshipGraph';
import { FileInfo } from '../models/fileInfo';

export interface MarkdownGeneratorInput {
  task: string;
  stats: TaskContextStats;
  extractedContexts: ExtractedFileContext[];
  relevanceResult: RelevanceResult;
  filesMap: Map<string, FileInfo>;
  graph: RelationshipGraph;
  includeProjectStructure?: boolean;
  includeCodeBlocks?: boolean;
  entryFile?: string;
  entryFiles?: string[];
  entryFunction?: string;
  aiExplanation?: string;
  generationMode?: 'generate-context' | 'explain-ollama' | 'full-analysis';
}

export class MarkdownGenerator {
  /**
   * Generates production-quality markdown context tailored to the active generation mode.
   */
  public static generateMarkdown(input: MarkdownGeneratorInput): string {
    const mode = input.generationMode || 'generate-context';

    if (mode === 'full-analysis') {
      return this.generateFullAnalysisMarkdown(input);
    } else if (mode === 'explain-ollama') {
      return this.generateExplainOllamaMarkdown(input);
    } else {
      return this.generateContextMarkdown(input);
    }
  }

  /**
   * Mode 1: Full Analysis — Comprehensive repository architecture and system guide (CLAUDE.md standard) with ZERO raw code blocks.
   */
  private static generateFullAnalysisMarkdown(input: MarkdownGeneratorInput): string {
    const { task, stats, aiExplanation } = input;
    const sections: string[] = [];

    sections.push('# ⚡ Codebase Architecture & System Guide (CLAUDE.md)\n');

    sections.push(`## Scope & Overview\n\n- **Project Focus:** ${task || 'Comprehensive Full Codebase Analysis'}\n- **Files Analyzed:** ${stats.filesAnalyzed}\n- **AI Analysis Model:** Ollama (${stats.aiModel || 'Local AI'})\n- **Generated Date:** ${new Date().toLocaleString()}\n\n---`);

    if (aiExplanation && aiExplanation.trim().length > 0) {
      sections.push(aiExplanation.trim());
    } else {
      sections.push(`## 1. Executive Summary & Application Purpose
Comprehensive architectural overview generated by AI Code Context Collector.

## 2. System Architecture & Directory Layout
Structured breakdown of repository modules, presentation layers, data layers, and services.

## 3. Core Modules & Feature Breakdown
Analysis of primary components, state managers, and controllers.

## 4. State Management & Data Flow Architecture
Overview of reactive state pipelines, dependency injection, and event propagation.

## 5. Persistence, Models & Backend Integration
Data schemas, local persistence, API connectors, and repositories.

## 6. Development Conventions, Scripts & Architecture Strengths
Coding standards, build scripts, test workflows, error handling, and reliability patterns.`);
    }

    return sections.join('\n\n');
  }

  /**
   * Mode 2: Explain with Ollama — Structured technical breakdown with or without code blocks.
   */
  private static generateExplainOllamaMarkdown(input: MarkdownGeneratorInput): string {
    const {
      task,
      extractedContexts,
      entryFile,
      entryFiles,
      entryFunction,
      aiExplanation,
      stats,
      includeCodeBlocks = true,
    } = input;

    const sections: string[] = [];

    sections.push('# 💡 Code & Feature Explanation\n');

    sections.push(`Task: ${task}\n\n---`);

    // Relevant Files
    const allFiles = extractedContexts.map((c) => `- \`${c.relativePath}\`${c.reason ? `: ${c.reason}` : ''}`);
    sections.push(`Relevant Files:\n${allFiles.length > 0 ? allFiles.join('\n') : '- No specific files selected'}`);

    // Call Chain
    const chainItems: string[] = [];
    const allAttachedFiles: string[] = [];
    if (entryFiles && entryFiles.length > 0) allAttachedFiles.push(...entryFiles);
    if (entryFile && !allAttachedFiles.includes(entryFile)) allAttachedFiles.push(entryFile);

    if (allAttachedFiles.length > 0) {
      chainItems.push(...allAttachedFiles.map((f) => `\`${f}\``));
    } else if (extractedContexts.length > 0) {
      chainItems.push(...extractedContexts.map((c) => `\`${c.relativePath}\``));
    }
    const callChainStr =
      chainItems.length > 0
        ? entryFunction
          ? `${chainItems[0]} (\`${entryFunction}\`) -> ` + chainItems.slice(1).join(' -> ')
          : chainItems.join(' -> ')
        : 'Entry point -> Core logic';
    sections.push(`Call Chain:\n${callChainStr}`);

    // Related Functions
    const functionsList: string[] = [];
    if (entryFunction) {
      functionsList.push(`- \`${entryFunction}\` (Target Entry Function / API)`);
    }
    extractedContexts.forEach((c) => {
      (c.symbols || [])
        .filter((s) => s.kind === 'function' || s.kind === 'method')
        .forEach((s) => {
          if (!functionsList.some((f) => f.includes(`\`${s.name}\``))) {
            functionsList.push(`- \`${s.name}\` (\`${c.relativePath}\`${s.startLine ? `:${s.startLine}` : ''})`);
          }
        });
    });
    sections.push(`Related Functions:\n${functionsList.length > 0 ? functionsList.join('\n') : '- (None identified)'}`);

    // Related Models
    const modelsList: string[] = [];
    extractedContexts.forEach((c) => {
      (c.symbols || [])
        .filter((s) => s.kind === 'model' || s.kind === 'interface' || s.kind === 'type' || s.kind === 'class')
        .forEach((s) => {
          if (!modelsList.some((m) => m.includes(`\`${s.name}\``))) {
            modelsList.push(`- \`${s.name}\` (\`${c.relativePath}\`)`);
          }
        });
    });
    sections.push(`Related Models:\n${modelsList.length > 0 ? modelsList.join('\n') : '- (None identified)'}`);

    // Current Logic
    sections.push(`Current Logic:\nHigh-level control flow and implementation logic for "${task}".`);

    // Potential Impact
    sections.push(`Potential Impact:\nImpact analysis across ${extractedContexts.length} referenced components and downstream dependencies.`);

    // Explanation
    if (aiExplanation && aiExplanation.trim().length > 0) {
      sections.push(`Explanation:\n\n${aiExplanation.trim()}`);
    } else {
      sections.push(`Explanation:\nDetailed step-by-step logic and component walkthrough for the analyzed task.`);
    }

    // Architecture
    sections.push(`# Architecture\n\nHigh-level architectural overview and component interaction diagram for the feature domain.`);

    // Code Snippets (Only when includeCodeBlocks === true)
    if (includeCodeBlocks) {
      const snippetLines: string[] = ['## Code Snippets\n'];
      extractedContexts.forEach((ctx, index) => {
        const fileNum = index + 1;
        snippetLines.push(`### ${fileNum}. \`${ctx.relativePath}\`\n`);
        if (ctx.reason) {
          snippetLines.push(`*Role:* ${ctx.reason}\n`);
        }
        if (ctx.isEntireFile && ctx.fullContent) {
          snippetLines.push(`\`\`\`${ctx.language}\n${ctx.fullContent}\n\`\`\`\n`);
        } else if (ctx.codeBlocks.length > 0) {
          for (const block of ctx.codeBlocks) {
            const symLabel = block.symbolName ? `\`${block.symbolName}\` ` : '';
            snippetLines.push(`**${symLabel}(Lines ${block.startLine}-${block.endLine})**:`);
            snippetLines.push(`\`\`\`${ctx.language}\n${block.code}\n\`\`\`\n`);
          }
        }
      });
      sections.push(snippetLines.join('\n'));
    }

    return sections.join('\n\n');
  }

  /**
   * Mode 3: Generate Context — Optimized, clean extraction of code blocks for Web AI (ChatGPT / Claude / Gemini).
   */
  private static generateContextMarkdown(input: MarkdownGeneratorInput): string {
    const {
      task,
      stats,
      extractedContexts,
      relevanceResult,
      filesMap,
      includeProjectStructure = true,
      entryFile,
      entryFiles,
      entryFunction,
    } = input;

    const sections: string[] = [];

    // Title
    sections.push('# AI Task Context\n');

    // Task Description
    sections.push(`## Task\n\n${task}\n\n---`);

    // Context Summary
    const aiText = stats.aiAssisted
      ? `Ollama / ${stats.aiModel || 'qwen2.5-coder:1.5b'}`
      : 'Deterministic Static Code Analysis';

    let summaryText = `## Context Summary\n\nGenerated locally by AI Code Context Collector.\n\nFiles analyzed: ${stats.filesAnalyzed}\nCandidate files: ${stats.candidateFiles}\nSelected files: ${stats.selectedFiles}\nSelected code blocks: ${stats.selectedCodeBlocks}\n\nAI assistance:\n${aiText}`;

    const allAttachedFiles: string[] = [];
    if (entryFiles && entryFiles.length > 0) allAttachedFiles.push(...entryFiles);
    if (entryFile && !allAttachedFiles.includes(entryFile)) allAttachedFiles.push(entryFile);

    if (allAttachedFiles.length > 0 || entryFunction) {
      summaryText += `\n\n**Entry Anchor:**`;
      if (allAttachedFiles.length === 1) {
        summaryText += `\n- File: \`${allAttachedFiles[0]}\``;
      } else if (allAttachedFiles.length > 1) {
        summaryText += `\n- Files:\n${allAttachedFiles.map((f) => `  - \`${f}\``).join('\n')}`;
      }
      if (entryFunction) {
        summaryText += `\n- Function / API Endpoint: \`${entryFunction}\``;
      }
    }

    if (stats.omittedFilesCount && stats.omittedFilesCount > 0) {
      summaryText += `\n\n> **Note**: ${stats.omittedFilesCount} candidate file(s) were omitted to preserve context size limits.`;
    }

    sections.push(`${summaryText}\n\n---`);

    // Project Structure
    if (includeProjectStructure) {
      const selectedRelPaths = extractedContexts.map((c) => c.relativePath);
      const tree = ProjectStructure.generateTree(selectedRelPaths);
      sections.push(`## Project Structure\n\n\`\`\`text\n${tree}\n\`\`\`\n\n---`);
    }

    // Relevant Files & Code Blocks
    sections.push('## Relevant Files\n');

    extractedContexts.forEach((ctx, index) => {
      const fileNum = index + 1;
      const fileLines: string[] = [];

      fileLines.push(`### ${fileNum}. ${ctx.relativePath}\n`);
      fileLines.push(`#### Why this file is relevant\n\n${ctx.reason}\n`);

      // Source Code
      fileLines.push('#### Source Code\n');
      if (ctx.isEntireFile && ctx.fullContent) {
        fileLines.push(`\`\`\`${ctx.language}\n${ctx.fullContent}\n\`\`\`\n`);
      } else if (ctx.codeBlocks.length > 0) {
        for (const block of ctx.codeBlocks) {
          if (block.symbolName) {
            fileLines.push(`**${block.symbolName}** (Lines ${block.startLine}-${block.endLine}):`);
          }
          fileLines.push(`\`\`\`${ctx.language}\n${block.code}\n\`\`\`\n`);
        }
      }

      sections.push(fileLines.join('\n'));
      sections.push('---\n');
    });

    // Important Symbols Table (if available)
    const symbolsTable = this.renderSymbolsTable(relevanceResult, extractedContexts);
    if (symbolsTable) {
      sections.push(`## Important Symbols\n\n${symbolsTable}\n\n---`);
    }

    // AI Instructions
    sections.push(`## AI Instructions

Use the supplied source code as the source of truth.

Before suggesting implementation:
1. Understand the existing architecture.
2. Identify the exact files that need changes.
3. Explain why each file needs modification.
4. Give implementation instructions step-by-step.
5. Do not invent APIs, functions, models, or variables.
6. Do not assume omitted files are irrelevant.
7. If more source code is required, explicitly request the exact file.
8. Preserve the existing architecture unless a change is necessary.`);

    return sections.join('\n\n');
  }

  private static renderSymbolsTable(
    relevanceResult: RelevanceResult,
    contexts: ExtractedFileContext[]
  ): string {
    const rows: string[] = [
      '| File | Symbol | Type | Reason |',
      '| ---- | ------ | ---- | ------ |',
    ];

    const contextMap = new Map(contexts.map((c) => [c.path, c.relativePath]));

    if (relevanceResult && relevanceResult.relevantSymbols && relevanceResult.relevantSymbols.length > 0) {
      for (const sym of relevanceResult.relevantSymbols) {
        const fileRel = contextMap.get(sym.file) || sym.file;
        rows.push(`| \`${fileRel}\` | \`${sym.symbol}\` | ${sym.type} | ${sym.reason} |`);
      }
    } else {
      for (const ctx of contexts) {
        if (ctx.symbols) {
          for (const sym of ctx.symbols.slice(0, 3)) {
            rows.push(`| \`${ctx.relativePath}\` | \`${sym.name}\` | ${sym.kind} | Core symbol in candidate file |`);
          }
        }
      }
    }

    return rows.length > 2 ? rows.join('\n') : '';
  }
}

